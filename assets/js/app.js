  function appendSearchParams(rawUrl, params) {
    if (!rawUrl) {
      return '';
    }

    try {
      const url = new URL(rawUrl);
      Object.entries(params || {}).forEach(([key, value]) => {
        if (value !== null && value !== undefined && value !== '') {
          url.searchParams.set(key, String(value));
        }
      });
      return url.toString();
    } catch (err) {
      return rawUrl;
    }
  }

