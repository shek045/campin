  function renderDetailPhotos(camp) {
    const photoSlots = Array.from(document.querySelectorAll('.detail-photo'));
    const photoUrls = [...new Set([
      ...(Array.isArray(camp.photoUrls) ? camp.photoUrls : []),
      camp.imageUrl
    ].map(normalizeImageUrl).filter(Boolean))];

    photoSlots.forEach((slot, index) => {
      const photoUrl = photoUrls[index] || '';
      const fallbackEmoji = camp.emoji || emojis[index % emojis.length];
      const fallbackBg = camp.bg || cardPalettes[index % cardPalettes.length];

      slot.style.background = sanitizeBackgroundColor(fallbackBg);
      slot.innerHTML = '';

      if (photoUrl) {
        const image = document.createElement('img');
        image.className = 'detail-photo-img';
        image.src = photoUrl;
        image.alt = String(camp.name || 'Campground photo');
        image.loading = 'lazy';
        image.referrerPolicy = 'no-referrer';
        image.addEventListener('error', () => {
          slot.textContent = String(fallbackEmoji || '🏕️');
        });
        slot.appendChild(image);
        if (camp.illustrativePhotoUrls?.includes(photoUrl)) {
          image.alt = `Illustrative photo, not verified for ${camp.name}`;
          const label = document.createElement('span');
          label.className = 'photo-source-label';
          label.textContent = 'Illustrative photo · Wikimedia';
          slot.appendChild(label);
        }
      } else {
        slot.textContent = String(fallbackEmoji || '🏕️');
      }
    });
  }

  async function fetchFallbackCampgroundPhotos(camp) {
    const query = [camp.name, camp.loc].filter(Boolean).join(' ').trim();
    if (!query) {
      return [];
    }

    const cacheKey = query.toLowerCase();
    pruneExpiringMap(photoLookupCache, PHOTO_LOOKUP_CACHE_MAX_ENTRIES);
    if (photoLookupCache.has(cacheKey)) {
      return photoLookupCache.get(cacheKey);
    }

    try {
      const res = await apiClient.getMediaPhotos(query);
      if (!res.ok) {
        photoLookupCache.set(cacheKey, []);
        return [];
      }

      const payload = await res.json();
      const photos = [...new Set((Array.isArray(payload?.photos) ? payload.photos : []).map(normalizeImageUrl).filter(Boolean))];
      photoLookupCache.set(cacheKey, photos);
      return photos;
    } catch (err) {
      photoLookupCache.set(cacheKey, []);
      return [];
    }
  }

  async function hydrateDetailPhotos(camp) {
    const existingPhotos = [...new Set([
      ...(Array.isArray(camp.photoUrls) ? camp.photoUrls : []),
      camp.imageUrl
    ].map(normalizeImageUrl).filter(Boolean))];

    if (existingPhotos.length >= 5) {
      return;
    }

    const fallbackPhotos = await fetchFallbackCampgroundPhotos(camp);
    if (!fallbackPhotos.length || !currentCamp || currentCamp.id !== camp.id) {
      return;
    }

    currentCamp = {
      ...currentCamp,
      photoUrls: [...new Set([...existingPhotos, ...fallbackPhotos])],
      illustrativePhotoUrls: [...new Set([...(currentCamp.illustrativePhotoUrls || []), ...fallbackPhotos])]
    };

    renderDetailPhotos(currentCamp);
  }

