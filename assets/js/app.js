  async function fetchGoogleReviews(camp) {
    const query = [camp?.name, camp?.loc].filter(Boolean).join(' ').trim();
    if (!query) {
      return { enabled: false, source: 'fallback', reviews: [], error: 'Missing campground query.' };
    }

    const cacheKey = query.toLowerCase();
    const now = Date.now();
    const cached = googleReviewsCache.get(cacheKey);
    if (cached && cached.expiresAt > now) {
      return cached.payload;
    }

    try {
      const res = await apiClient.getGoogleReviews(query);
      const payload = await res.json();

      if (!res.ok) {
        const fallbackPayload = {
          enabled: false,
          source: 'fallback',
          reviews: [],
          error: String(payload?.error || 'Google reviews unavailable.').trim()
        };
        googleReviewsCache.set(cacheKey, {
          expiresAt: now + GOOGLE_REVIEWS_CACHE_TTL_MS,
          payload: fallbackPayload
        });
        return fallbackPayload;
      }

      const normalized = {
        enabled: payload?.enabled === true,
        source: String(payload?.source || 'google').trim(),
        placeName: String(payload?.placeName || '').trim(),
        rating: Number.isFinite(Number(payload?.rating)) ? Number(payload.rating) : null,
        userRatingsTotal: Number.isFinite(Number(payload?.userRatingsTotal)) ? Number(payload.userRatingsTotal) : null,
        placeUrl: String(payload?.placeUrl || '').trim(),
        reviews: (Array.isArray(payload?.reviews) ? payload.reviews : []).slice(0, 5),
        error: String(payload?.error || '').trim()
      };

      googleReviewsCache.set(cacheKey, {
        expiresAt: now + GOOGLE_REVIEWS_CACHE_TTL_MS,
        payload: normalized
      });
      return normalized;
    } catch (err) {
      const fallbackPayload = {
        enabled: false,
        source: 'fallback',
        reviews: [],
        error: 'Google reviews request failed.'
      };
      googleReviewsCache.set(cacheKey, {
        expiresAt: now + GOOGLE_REVIEWS_CACHE_TTL_MS,
        payload: fallbackPayload
      });
      return fallbackPayload;
    }
  }

