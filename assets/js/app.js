  function getRequiredClarificationQuestions(intent) {
    if (!intent || intent.enabled !== true) {
      return [];
    }

    const questions = [];
    const intentQuestions = Array.isArray(intent.clarificationQuestions) ? intent.clarificationQuestions : [];

    if (!String(intent.location || '').trim()) {
      questions.push(intentQuestions[0] || 'What location, park, or region should I search around?');
    }

    if (!Number.isFinite(Number(intent.partySize)) || Number(intent.partySize) <= 0) {
      questions.push(intentQuestions.find(question => /group|people|campers/i.test(question)) || 'How many campers are in your group?');
    }

    if (!Array.isArray(intent.priorities) || intent.priorities.length === 0) {
      questions.push(intentQuestions.find(question => /prefer|amenit|style|budget|waterfront|rv|tent|dog/i.test(question)) || 'What matters most for this trip: hookups, waterfront, dog-friendly, quiet, budget, or something else?');
    }

    return [...new Set(questions)].slice(0, 3);
  }

  function buildClarificationMessage(questions) {
    if (!Array.isArray(questions) || questions.length === 0) {
      return '';
    }

    return `I need a few details before I search live inventory:\n${questions.map((question, index) => `${index + 1}. ${question}`).join('\n')}`;
  }

  async function runSearch(queryOverride) {
    await loadAppConfig();

    const rawQuery = String(queryOverride || getSearchQuery() || 'Quiet lakeside, dog-friendly, near Seattle').trim();
    const q = pendingClarification
      ? `${pendingClarification.baseQuery}. Additional user details: ${rawQuery}`
      : rawQuery;

    syncSearchInputs('');
    pushChatMessage('user', rawQuery);
    setPendingAssistantMessage(pendingClarification ? 'Incorporating those details into your trip request...' : 'Understanding your trip request...');
    showView('results');
    setLoadingState(true, 'Analyzing your trip request...');
    renderResultsGrid();

    try {
      lastIntent = await fetchIntentParse(q);
      const clarificationQuestions = getRequiredClarificationQuestions(lastIntent);

      if (clarificationQuestions.length > 0) {
        pendingClarification = {
          baseQuery: q,
          questions: clarificationQuestions
        };
        campsites = [];
        inventorySourceText = 'Waiting for required trip details';
        setLoadingState(false);
        renderResultsGrid();
        resolvePendingAssistantMessage(buildClarificationMessage(clarificationQuestions), 'warning');
        return;
      }

      pendingClarification = null;
      setPendingAssistantMessage('Searching live Recreation.gov and NPS inventory...');
      setLoadingState(true, 'Fetching live inventory from Recreation.gov + NPS...');
      renderResultsGrid();

      const live = await fetchLiveInventory(q, lastIntent);
      if (live.length > 0) {
        campsites = live;
      } else {
        if (lastIntent && lastIntent.enabled) {
          campsites = [];
          inventorySourceText = 'No live campsites matched your intent. Try broadening your query or relaxing constraints';
        } else if (APP_CONFIG.demoMode) {
          campsites = [...mockCampsites];
          inventorySourceText = 'Demo mode inventory (live APIs unavailable or not configured)';
        } else {
          campsites = [];
          inventorySourceText = 'No live campsites were returned. Check API keys, query breadth, or enable demo mode';
        }
      }
      resolvePendingAssistantMessage(buildSearchResultMessage(q, campsites, lastIntent), campsites.length ? 'default' : 'warning');
    } catch (err) {
      console.error('Live inventory search failed:', err);
      if (APP_CONFIG.demoMode) {
        campsites = [...mockCampsites];
        inventorySourceText = 'Demo mode inventory (live fetch failed)';
        resolvePendingAssistantMessage('The live search failed, so I loaded demo inventory because demo mode is enabled.', 'warning');
      } else {
        campsites = [];
        inventorySourceText = 'Live fetch failed. Check the proxy server, provider keys, or Foundry settings';
        resolvePendingAssistantMessage('The live search failed and demo mode is off, so no mock results were shown. Check the proxy server or API credentials.', 'warning');
      }
    }

    setLoadingState(false);
    renderResultsGrid();
  }

