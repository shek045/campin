  async function resolveNearestCityState(lat, lon) {
    const latNum = Number(lat);
    const lonNum = Number(lon);
    if (!Number.isFinite(latNum) || !Number.isFinite(lonNum)) {
      return '';
    }

    const cached = getCachedLocationLabel(latNum, lonNum);
    if (cached) {
      return cached;
    }

    try {
      const res = await apiClient.reverseGeocode(latNum, lonNum);
      if (!res.ok) {
        return '';
      }

      const data = await res.json();
      const label = String(data?.locationLabel || '').trim();
      if (label) {
        setCachedLocationLabel(latNum, lonNum, label);
        return label;
      }
    } catch (error) {
      return '';
    }

    return '';
  }

