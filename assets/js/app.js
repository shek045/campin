  function firstSentence(text) {
    const cleaned = String(text || '')
      .replace(/^\s*overview\s*[:\-]?\s*/i, '')
      .replace(/\s+/g, ' ')
      .trim();
    if (!cleaned) {
      return '';
    }

    const match = cleaned.match(/[^.!?]+[.!?]/);
    if (match) {
      return match[0].trim();
    }

    return `${cleaned.replace(/[.!?]+$/g, '')}.`;
  }

