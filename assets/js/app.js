  async function fetchGoogleReviews(camp) {
    const query = [camp?.name, camp?.loc].filter(Boolean).join(' ').trim();
    if (!query) {
      return { enabled: false, source: 'fallback', reviews: [], error: 'Missing campground query.' };
    }

    const cacheKey = query.toLowerCase();
    const now = Date.now();
    pruneExpiringMap(googleReviewsCache, GOOGLE_REVIEWS_CACHE_MAX_ENTRIES);
    const cached = googleReviewsCache.get(cacheKey);
    if (cached && cached.expiresAt > now) {
      return cached.payload;
    }

    const inFlight = googleReviewsInFlight.get(cacheKey);
    if (inFlight) {
      return inFlight;
    }

    const reviewRequestPromise = (async () => {
      let timeoutId = null;
      const controller = typeof AbortController !== 'undefined' ? new AbortController() : null;
      if (controller) {
        timeoutId = setTimeout(() => controller.abort(), GOOGLE_REVIEWS_REQUEST_TIMEOUT_MS);
      }

      try {
        const res = await apiClient.getGoogleReviews(query, controller ? { signal: controller.signal } : undefined);
        const payload = await res.json();

        if (!res.ok) {
          const fallbackPayload = {
            enabled: false,
            source: 'fallback',
            reviews: [],
            error: String(payload?.error || 'Google reviews unavailable.').trim()
          };
          googleReviewsCache.set(cacheKey, {
            expiresAt: now + GOOGLE_REVIEWS_CACHE_TTL_MS,
            payload: fallbackPayload
          });
          return fallbackPayload;
        }

        const normalized = {
          enabled: payload?.enabled === true,
          source: String(payload?.source || 'google').trim(),
          placeName: String(payload?.placeName || '').trim(),
          rating: knownNumber(payload?.rating),
          userRatingsTotal: knownNumber(payload?.userRatingsTotal),
          placeUrl: String(payload?.placeUrl || '').trim(),
          reviews: (Array.isArray(payload?.reviews) ? payload.reviews : []).slice(0, 5),
          error: String(payload?.error || '').trim()
        };

        googleReviewsCache.set(cacheKey, {
          expiresAt: now + GOOGLE_REVIEWS_CACHE_TTL_MS,
          payload: normalized
        });
        return normalized;
      } catch (err) {
        const didTimeout = String(err?.name || '').toLowerCase() === 'aborterror';
        const fallbackPayload = {
          enabled: false,
          source: 'fallback',
          reviews: [],
          error: didTimeout
            ? 'Google reviews timed out. Try opening this listing again in a moment.'
            : 'Google reviews request failed.'
        };
        googleReviewsCache.set(cacheKey, {
          expiresAt: now + GOOGLE_REVIEWS_CACHE_TTL_MS,
          payload: fallbackPayload
        });
        return fallbackPayload;
      } finally {
        if (timeoutId) {
          clearTimeout(timeoutId);
        }
      }
    })();

    googleReviewsInFlight.set(cacheKey, reviewRequestPromise);
    try {
      return await reviewRequestPromise;
    } finally {
      googleReviewsInFlight.delete(cacheKey);
    }
  }

  function renderGoogleReviews(camp, reviewPayload) {
    const reviewsEl = document.getElementById('d-reviews');
    if (!reviewsEl || !camp) {
      return;
    }

    const rating = knownNumber(reviewPayload?.rating);
    const ratingsTotal = knownNumber(reviewPayload?.userRatingsTotal);
    const placeName = String(reviewPayload?.placeName || camp.name || 'Google place').trim();
    const placeUrl = safeHttpUrl(reviewPayload?.placeUrl);
    const reviews = Array.isArray(reviewPayload?.reviews) ? reviewPayload.reviews : [];

    if (reviews.length > 0) {
      if (currentCamp && currentCamp.id === camp.id) {
        currentCamp = {
          ...currentCamp,
          googleReviewSummary: {
            placeName,
            rating,
            userRatingsTotal: ratingsTotal,
            highlights: reviews.slice(0, 2).map(review => truncateText(String(review?.text || ''), 120)).filter(Boolean)
          }
        };
      }

      const headerCard = `
        <div class="review-card">
          <div class="review-header">
            <span class="reviewer">Google rating snapshot</span>
            <span class="review-date">Live</span>
          </div>
          <div class="review-text">${escapeHtml(placeName)}${Number.isFinite(rating) ? ` is rated ${rating.toFixed(1)}${Number.isFinite(ratingsTotal) ? ` from ${Math.round(ratingsTotal)} reviews` : ''}.` : ' has active Google reviews.'} ${placeUrl ? `<a href="${escapeHtml(placeUrl)}" target="_blank" rel="noopener noreferrer">Open on Google Maps</a>.` : ''}</div>
        </div>`;

      const reviewCards = reviews.slice(0, 5).map(review => {
        const author = escapeHtml(String(review?.author || 'Google user'));
        const text = escapeHtml(String(review?.text || ''));
        const relativeTime = escapeHtml(String(review?.relativeTime || ''));
        const stars = Number.isFinite(Number(review?.rating))
          ? '★'.repeat(Math.max(1, Math.min(5, Math.round(Number(review.rating)))))
          : 'Google review';

        return `
          <div class="review-card">
            <div class="review-header">
              <span class="reviewer">${author} ${stars}</span>
              <span class="review-date">${relativeTime || 'Recent'}</span>
            </div>
            <div class="review-text">${text}</div>
          </div>`;
      }).join('');

      reviewsEl.innerHTML = `${headerCard}${reviewCards}`;
      if (currentCamp && currentCamp.id === camp.id) {
        renderDetailListingFields(currentCamp, false);
      }
      return;
    }

    const fallbackReason = escapeHtml(String(reviewPayload?.error || 'No Google reviews were returned for this campground.'));
    const fallbackRatingText = knownNumber(camp?.rating) !== null
      ? `${Number(camp.rating).toFixed(2)} ${camp.isDemo ? 'illustrative demo' : 'provider'} rating.`
      : 'Rating details are unavailable for this listing.';

    reviewsEl.innerHTML = `
      <div class="review-card">
        <div class="review-header">
          <span class="reviewer">Google Reviews unavailable</span>
          <span class="review-date">Live</span>
        </div>
        <div class="review-text">${fallbackReason}</div>
      </div>
      <div class="review-card">
        <div class="review-header">
          <span class="reviewer">Provider rating snapshot</span>
          <span class="review-date">Fallback</span>
        </div>
        <div class="review-text">${fallbackRatingText}</div>
      </div>`;
    if (currentCamp && currentCamp.id === camp.id) {
      currentCamp = {
        ...currentCamp,
        googleReviewSummary: {
          placeName,
          rating: knownNumber(camp?.rating),
          userRatingsTotal: knownNumber(camp?.reviews),
          highlights: []
        }
      };
      renderDetailListingFields(currentCamp, false);
    }
  }

