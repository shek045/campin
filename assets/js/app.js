  function buildRecreationBookingUrl(campgroundId, bookingWindow) {
    if (!campgroundId) {
      return '';
    }

    const base = `https://www.recreation.gov/camping/campgrounds/${encodeURIComponent(String(campgroundId))}`;
    return appendSearchParams(base, {
      tab: 'seasons',
      checkin: bookingWindow?.checkIn || null,
      checkout: bookingWindow?.checkOut || null,
      adults: bookingWindow?.adults || null
    });
  }

  function buildCampBookingTarget(camp, bookingWindow) {
    if (!camp) {
      return {
        providerLabel: 'Provider website',
        url: '',
        ctaLabel: 'Search provider website'
      };
    }

    const recId = camp.recreationCampgroundId || extractRecreationCampgroundId(camp.bookingUrl || '');
    if (recId) {
      return {
        providerLabel: 'Recreation.gov',
        url: buildRecreationBookingUrl(recId, bookingWindow),
        ctaLabel: 'Book on Recreation.gov'
      };
    }

    if (camp.bookingUrl) {
      return {
        providerLabel: camp.sourceProvider === 'nps' ? 'NPS reservation partner' : 'Campground provider',
        url: appendSearchParams(camp.bookingUrl, {
          checkin: bookingWindow?.checkIn || null,
          checkout: bookingWindow?.checkOut || null,
          adults: bookingWindow?.adults || null
        }),
        ctaLabel: 'Book on provider site'
      };
    }

    const npsSearchUrl = appendSearchParams('https://www.nps.gov/search/', {
      query: `${camp.name || 'campground'} ${camp.loc || ''}`.trim()
    });

    return {
      providerLabel: 'NPS',
      url: npsSearchUrl,
      ctaLabel: 'Search on NPS'
    };
  }

