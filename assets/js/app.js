  async function hydrateCardLocationLabels(cards) {
    const rows = Array.isArray(cards) ? cards : [];
    const hydrated = [];

    for (const card of rows) {
      const existing = String(card?.loc || '').trim();
      if (!isCoordinateLocation(existing)) {
        hydrated.push(card);
        continue;
      }

      const label = await resolveNearestCityState(card.lat, card.lon);
      if (!label) {
        const cityFallback = String(card?.cityName || '').trim();
        const stateFallback = String(card?.stateCode || '').trim();
        const fallbackLabel = cityFallback && stateFallback
          ? `${cityFallback}, ${stateFallback}`
          : (stateFallback || 'United States');
        hydrated.push(card);
        hydrated[hydrated.length - 1] = {
          ...hydrated[hydrated.length - 1],
          loc: fallbackLabel,
          pinLocation: formatCoordinateLocation(card.lat, card.lon)
        };
        continue;
      }

      hydrated.push({
        ...card,
        loc: label,
        pinLocation: formatCoordinateLocation(card.lat, card.lon)
      });
    }

    return hydrated;
  }

