  function buildQueryCandidates(rawQuery) {
    const normalized = String(rawQuery || '').toLowerCase().trim();
    if (!normalized) {
      return ['campground'];
    }

    const stopWords = new Set([
      'quiet', 'dog-friendly', 'dog', 'friendly', 'near', 'this', 'weekend', 'with', 'and',
      'site', 'sites', 'want', 'to', 'camp', 'camps', 'please', 'find', 'me', 'a', 'an', 'the'
    ]);

    const words = normalized
      .replace(/[^a-z0-9\s]/g, ' ')
      .split(/\s+/)
      .filter(w => w && !stopWords.has(w));

    const locationHintMatch = normalized.match(/(?:near|in|around)\s+([a-z\s]+)/i);
    const locationHint = locationHintMatch ? locationHintMatch[1].trim().split(/\s+/).slice(0, 2).join(' ') : '';

    const candidates = [
      normalized,
      locationHint ? `${locationHint} campground` : '',
      words.slice(0, 3).join(' '),
      words.slice(0, 3).join(' ') ? `${words.slice(0, 3).join(' ')} campground` : '',
      words.includes('seattle') ? 'seattle washington campground' : '',
      words.includes('washington') ? 'washington campground' : '',
      'campground'
    ].filter(Boolean);

    return [...new Set(candidates)];
  }

  function buildQueryCandidatesFromIntent(rawQuery, intent) {
    const base = buildQueryCandidates(rawQuery);
    if (!intent || intent.enabled !== true) {
      return base;
    }

    const enriched = [
      intent.queryRewrite || '',
      intent.location ? `${intent.location} campground` : '',
      intent.location || '',
      ...(Array.isArray(intent.priorities) ? intent.priorities.map(p => `${p} campground`) : [])
    ].filter(Boolean);

    return [...new Set([...enriched, ...base])];
  }

