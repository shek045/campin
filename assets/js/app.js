  function dedupeInventoryCards(cards) {
    const seen = new Set();
    return cards.filter(card => {
      const byUrl = String(card?.bookingUrl || '').trim().toLowerCase();
      const byNameLoc = `${String(card?.name || '').trim().toLowerCase()}::${String(card?.loc || '').trim().toLowerCase()}`;
      const key = byUrl || byNameLoc;
      if (!key) {
        return true;
      }
      if (seen.has(key)) {
        return false;
      }
      seen.add(key);
      return true;
    });
  }

  function normalizeRegionFromLocation(loc = '', fallbackRegion = 'all') {
    const match = String(loc || '').match(/,\s*([A-Z]{2})\b/);
    const stateCode = match ? match[1].toUpperCase() : '';

    if (!stateCode) {
      return fallbackRegion;
    }

    if (REGION_STATES.rockies.includes(stateCode)) {
      return 'rockies';
    }
    if (REGION_STATES.northeast.includes(stateCode)) {
      return 'northeast';
    }
    if (REGION_STATES.midwest.includes(stateCode)) {
      return 'midwest';
    }
    if (REGION_STATES.south.includes(stateCode)) {
      return 'south';
    }
    if (REGION_STATES.west.includes(stateCode)) {
      return 'west';
    }

    return fallbackRegion;
  }

