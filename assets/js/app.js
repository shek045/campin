  function setPendingAssistantMessage(text) {
    if (pendingAssistantMessageId === null) {
      pendingAssistantMessageId = nextChatMessageId();
      searchConversation.push({
        id: pendingAssistantMessageId,
        role: 'assistant',
        tone: 'loading',
        text
      });
    } else {
      const pending = searchConversation.find(message => message.id === pendingAssistantMessageId);
      if (pending) {
        pending.text = text;
        pending.tone = 'loading';
      }
    }

    renderChatThreads();
  }

  function resolvePendingAssistantMessage(text, tone = 'default') {
    if (pendingAssistantMessageId === null) {
      pushChatMessage('assistant', text, { tone });
      return;
    }

    const pending = searchConversation.find(message => message.id === pendingAssistantMessageId);
    if (pending) {
      pending.text = text;
      pending.tone = tone;
    }
    pendingAssistantMessageId = null;
    renderChatThreads();
  }

